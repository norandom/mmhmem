//! The `BoilerplateWriter` component (task 6.1; design.md "services layer" /
//! "Components and Interfaces" BoilerplateWriter row; requirements.md
//! Req 4.1-4.4, 10.1).
//!
//! `boilerplate_write` sends the reference file + spec to the worker model
//! (Req 4.1), strips markdown fences, writes the generated code straight to
//! the target path, and returns a one-line ack with SHA-256, line count,
//! worker model, and latency (Req 4.2) — zero frontier input/output tokens
//! for reference reading and generation. BOTH the target and the reference
//! path are confined to `AGENT_MEM_ALLOWED_ROOTS` (amended rule); a reference
//! outside the roots is rejected and audited BEFORE any content is sent to
//! the worker (no arbitrary-file exfiltration). A missing reference errors
//! and writes nothing (Req 4.3). Every completed write is audited
//! (IO_SHUNT_CODE_WRITE) and breadcrumbed (Req 4.4).

use std::path::PathBuf;
use std::time::Instant;

use crate::config::Config;
use crate::services::paths::{AllowedRoots, PathError};
use crate::services::session_bus::SessionBus;
use crate::services::shunt_types::CallCtx;
use crate::services::stats;
use crate::services::worker::{WorkerClient, WorkerUsage};
use crate::storage::audit::{sha256_hex, AuditEventType, AuditWriter};
use crate::storage::db::Db;

/// One boilerplate_write call's input (bundled to stay under the clippy
/// 7-arg limit, Req 13).
#[derive(Debug, Clone)]
pub struct WriteRequest<'a> {
    /// Project name.
    pub project: &'a str,
    /// Calling harness.
    pub harness: &'a str,
    /// Workspace task ID, if known.
    pub task: Option<&'a str>,
    /// Target path to write (confined).
    pub target: &'a str,
    /// Reference file path (confined; its content goes to the worker).
    pub reference: &'a str,
    /// Specification prompt for the worker.
    pub spec: &'a str,
}

impl<'a> WriteRequest<'a> {
    /// The shared call context.
    pub fn ctx(&self) -> CallCtx<'a> {
        CallCtx {
            project: self.project,
            harness: self.harness,
            task: self.task,
        }
    }
}

/// One-line confirmation returned to the agent (Req 4.2).
#[derive(Debug, Clone)]
pub struct WriteAck {
    /// SHA-256 hex of the written file.
    pub sha256: String,
    /// Line count of the written file.
    pub lines: usize,
    /// Worker model that generated the code.
    pub model: String,
    /// Worker round-trip latency in ms.
    pub latency_ms: u64,
    /// Estimated avoided frontier input tokens (reference not read by frontier).
    pub avoided_input_tokens_est: u64,
    /// Estimated avoided frontier output tokens (boilerplate not generated by frontier).
    pub avoided_output_tokens_est: u64,
}

/// boilerplate_write errors.
#[derive(Debug)]
pub enum BoilerplateError {
    /// No worker model configured (Req 9.4).
    WorkerNotConfigured,
    /// Worker call failed (audited as WORKER_ERROR, Req 6.3).
    Worker(String),
    /// Reference file does not exist — nothing is written (Req 4.3).
    ReferenceNotFound(String),
    /// Target path outside allowed roots (audited).
    TargetOutsideRoots(PathBuf),
    /// Reference path outside allowed roots (audited; zero bytes sent to worker).
    ReferenceOutsideRoots(PathBuf),
    /// IO error.
    Io(String),
}

/// Successful worker output plus everything `persist` needs to write, audit,
/// and ack it (bundled to stay under the clippy 7-arg limit).
struct Generated {
    /// Confined target path.
    target: PathBuf,
    /// Confined reference path (audit details only at this point).
    reference: PathBuf,
    /// Raw (possibly fenced) worker output.
    raw_code: String,
    /// Worker-reported token usage (Req 10.2).
    usage: WorkerUsage,
    /// Worker round-trip latency in ms.
    latency_ms: u64,
    /// Reference file length in chars (Req 10.1 estimate input).
    reference_chars: usize,
}

impl std::fmt::Display for BoilerplateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            BoilerplateError::WorkerNotConfigured => {
                write!(f, "worker model not configured (WORKER_MODEL)")
            }
            BoilerplateError::Worker(e) => write!(f, "worker model call failed: {e}"),
            BoilerplateError::ReferenceNotFound(p) => write!(f, "reference file not found: {p}"),
            BoilerplateError::TargetOutsideRoots(p) => {
                write!(
                    f,
                    "target path outside AGENT_MEM_ALLOWED_ROOTS: {}",
                    p.display()
                )
            }
            BoilerplateError::ReferenceOutsideRoots(p) => {
                write!(
                    f,
                    "reference path outside AGENT_MEM_ALLOWED_ROOTS: {}",
                    p.display()
                )
            }
            BoilerplateError::Io(e) => write!(f, "io error: {e}"),
        }
    }
}

impl std::error::Error for BoilerplateError {}

/// The boilerplate write shunter (design.md BoilerplateWriter).
#[derive(Clone)]
pub struct BoilerplateWriter {
    db: Db,
    audit: AuditWriter,
    bus: Option<SessionBus>,
    worker: Option<WorkerClient>,
    roots: AllowedRoots,
}

impl BoilerplateWriter {
    /// New writer from config + parts. Worker may be absent (lazy, Req 9.4).
    pub fn new(
        db: Db,
        audit: AuditWriter,
        config: &Config,
        bus: Option<SessionBus>,
        worker: Option<WorkerClient>,
    ) -> Self {
        Self {
            db,
            audit,
            bus,
            worker,
            roots: AllowedRoots::from_config(config),
        }
    }

    /// Executes one boilerplate_write (Req 4.1-4.4).
    pub async fn write(&self, req: &WriteRequest<'_>) -> Result<WriteAck, BoilerplateError> {
        let ctx = req.ctx();
        // The target does not exist yet: confine via the nearest existing
        // ancestor (still blocks `..` traversal out of the allowed roots).
        let target = self.confine_new_audited(req.target, &ctx)?;
        // Confine the reference BEFORE reading it or calling the worker:
        // an out-of-roots reference must send zero bytes to the worker.
        let reference = self.confine_audited(req.reference, &ctx, false)?;
        if !reference.is_file() {
            return Err(BoilerplateError::ReferenceNotFound(
                req.reference.to_string(),
            ));
        }
        let reference_raw = tokio::fs::read_to_string(&reference)
            .await
            .map_err(|e| BoilerplateError::Io(e.to_string()))?;
        let reference_chars = reference_raw.len();
        let (raw_code, usage, latency_ms) = self
            .generate(&ctx, &target, &reference, reference_raw, req.spec)
            .await?;
        self.persist(
            &ctx,
            Generated {
                target,
                reference,
                raw_code,
                usage,
                latency_ms,
                reference_chars,
            },
        )
        .await
    }

    /// Worker model name for acks/audits (empty when no worker configured).
    fn worker_model(&self) -> &str {
        self.worker.as_ref().map(WorkerClient::model).unwrap_or("")
    }

    /// Delegates generation to the worker model; WORKER_ERROR is audited on
    /// failure (Req 4.2, 6.3). Returns raw (possibly fenced) code + usage.
    async fn generate(
        &self,
        ctx: &CallCtx<'_>,
        target: &std::path::Path,
        reference: &std::path::Path,
        reference_raw: String,
        spec: &str,
    ) -> Result<(String, WorkerUsage, u64), BoilerplateError> {
        let worker = self
            .worker
            .as_ref()
            .ok_or(BoilerplateError::WorkerNotConfigured)?;
        let payload = format!(
            "<file path=\"{}\">\n{}\n</file>",
            reference.display(),
            reference_raw
        );
        let t0 = Instant::now();
        let (raw_code, usage) = worker.generate_code(&payload, spec).await.map_err(|e| {
            let _ = self.audit.write_event(
                AuditEventType::WorkerError,
                ctx.harness,
                ctx.project,
                serde_json::json!({"target": target.display().to_string(), "error": e.to_string()}),
            );
            BoilerplateError::Worker(e.to_string())
        })?;
        Ok((raw_code, usage, t0.elapsed().as_millis() as u64))
    }

    /// Strips fences, writes the file, then audits + records stats +
    /// breadcrumb and returns the one-line ack (Req 4.2-4.4).
    async fn persist(
        &self,
        ctx: &CallCtx<'_>,
        gen: Generated,
    ) -> Result<WriteAck, BoilerplateError> {
        let Generated {
            target,
            reference,
            raw_code,
            usage,
            latency_ms,
            reference_chars,
        } = gen;
        let code = strip_fences(&raw_code);
        if let Some(parent) = target.parent() {
            tokio::fs::create_dir_all(parent)
                .await
                .map_err(|e| BoilerplateError::Io(e.to_string()))?;
        }
        tokio::fs::write(&target, &code)
            .await
            .map_err(|e| BoilerplateError::Io(e.to_string()))?;
        let sha = sha256_hex(code.as_bytes());
        let lines = code.lines().count();
        let (est_in, est_out) = stats::estimate_code_write(reference_chars, code.len());
        let details = serde_json::json!({
            "target": crate::storage::audit::redact_secrets(&target.display().to_string()),
            "reference": crate::storage::audit::redact_secrets(&reference.display().to_string()),
            "sha256": sha, "lines": lines, "worker_model": self.worker_model(),
            "latency_ms": latency_ms, "worker_prompt_tokens": usage.prompt_tokens,
            "worker_completion_tokens": usage.completion_tokens,
            "avoided_input_tokens_est": est_in, "avoided_output_tokens_est": est_out,
        });
        let _ = self.audit.write_event(
            AuditEventType::IoShuntCodeWrite,
            ctx.harness,
            ctx.project,
            details,
        );
        self.record_stat(ctx, est_in, est_out, usage, &target, &sha);
        let resource = target.display().to_string();
        self.crumb(
            ctx,
            "boilerplate_write",
            &resource,
            &format!("wrote {lines} lines to {}", target.display()),
        )
        .await;
        Ok(WriteAck {
            sha256: sha,
            lines,
            model: self.worker_model().to_string(),
            latency_ms,
            avoided_input_tokens_est: est_in,
            avoided_output_tokens_est: est_out,
        })
    }

    /// Confine + audit a not-yet-existing write target (nearest existing
    /// ancestor is canonicalized, so `..` traversal out of the roots fails).
    fn confine_new_audited(
        &self,
        raw: &str,
        ctx: &CallCtx<'_>,
    ) -> Result<PathBuf, BoilerplateError> {
        match self.roots.confine_new_file(raw) {
            Ok(p) => Ok(p),
            Err(PathError::NotFound(p)) => {
                Err(BoilerplateError::Io(format!("target not found: {p}")))
            }
            Err(PathError::OutsideRoots(p)) => {
                let _ = self.audit.write_event(
                    AuditEventType::Error,
                    ctx.harness,
                    ctx.project,
                    serde_json::json!({
                        "error": "target_outside_allowed_roots",
                        "path": p.display().to_string(),
                    }),
                );
                Err(BoilerplateError::TargetOutsideRoots(p))
            }
        }
    }

    /// Confine + audit an existing path (the reference file).
    fn confine_audited(
        &self,
        raw: &str,
        ctx: &CallCtx<'_>,
        _is_target: bool,
    ) -> Result<PathBuf, BoilerplateError> {
        match self.roots.confine(raw) {
            Ok(p) => Ok(p),
            Err(PathError::NotFound(p)) => Err(BoilerplateError::ReferenceNotFound(p)),
            Err(PathError::OutsideRoots(p)) => {
                let _ = self.audit.write_event(
                    AuditEventType::Error,
                    ctx.harness,
                    ctx.project,
                    serde_json::json!({
                        "error": "reference_outside_allowed_roots",
                        "path": p.display().to_string(),
                    }),
                );
                Err(BoilerplateError::ReferenceOutsideRoots(p))
            }
        }
    }

    /// One token_stats row (kind=code_write, Req 10.1/10.3).
    fn record_stat(
        &self,
        ctx: &CallCtx<'_>,
        est_in: u64,
        est_out: u64,
        usage: crate::services::worker::WorkerUsage,
        target: &std::path::Path,
        sha: &str,
    ) {
        let row = stats::TokenStatRow {
            project: ctx.project.to_string(),
            task_id: ctx.task.map(str::to_string),
            harness: ctx.harness.to_string(),
            kind: stats::kind::CODE_WRITE,
            avoided_input_tokens_est: est_in,
            avoided_output_tokens_est: est_out,
            worker_prompt_tokens: Some(usage.prompt_tokens),
            worker_completion_tokens: Some(usage.completion_tokens),
            details: serde_json::json!({"target": target.display().to_string(), "sha256": sha}),
        };
        let db = self.db.clone();
        tokio::spawn(async move {
            if let Err(e) = stats::record(&db, row).await {
                tracing::warn!("token_stats insert failed: {e}");
            }
        });
    }

    /// Breadcrumb when a session bus is attached (Req 4.4).
    async fn crumb(&self, ctx: &CallCtx<'_>, tool: &str, resource: &str, summary: &str) {
        if let Some(bus) = &self.bus {
            let task = ctx.task.unwrap_or(ctx.project);
            if let Err(e) = bus
                .breadcrumb(
                    ctx.project,
                    task,
                    ctx.harness,
                    tool,
                    Some(resource),
                    summary,
                )
                .await
            {
                tracing::warn!("breadcrumb failed: {e}");
            }
        }
    }
}

/// Strips a single surrounding markdown code fence (```lang ... ```) from
/// worker output; returns the input unchanged when no fence is present
/// (Req 4.2).
pub fn strip_fences(code: &str) -> String {
    let trimmed = code.trim_start();
    let Some(after_open) = trimmed.strip_prefix("```") else {
        return code.to_string();
    };
    let Some(nl) = after_open.find('\n') else {
        return String::new();
    };
    let body = &after_open[nl + 1..];
    match body.rfind("```") {
        Some(close) => {
            let inner = body[..close].trim_end();
            if inner.is_empty() {
                String::new()
            } else {
                format!("{inner}\n")
            }
        }
        None => body.trim_end().to_string() + "\n",
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strip_fences_removes_lang_fence() {
        let out = strip_fences("```rust\nfn main() {}\n```\n");
        assert_eq!(out, "fn main() {}\n");
    }

    #[test]
    fn strip_fences_removes_plain_fence_and_keeps_inner_newlines() {
        let out = strip_fences("```\nline1\nline2\n```");
        assert_eq!(out, "line1\nline2\n");
    }

    #[test]
    fn strip_fences_passes_through_unfenced_code() {
        let src = "fn main() { println!(\"hi\"); }\n";
        assert_eq!(strip_fences(src), src);
    }

    #[test]
    fn strip_fences_unclosed_fence_returns_body() {
        assert_eq!(strip_fences("```ts\nlet x = 1;\n"), "let x = 1;\n");
    }
}
